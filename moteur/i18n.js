/** Résumé des règles, une ligne par règle, dans la langue choisie. */
export function resumeReglesTraduit(r, t) {
  const lignes = [];
  const plateau = r.forme === 'croix' ? t('rPlateauCroix') : t('rPlateauCarre', { t: r.taille });
  lignes.push(t('rPions', { plateau, n: r.nbPions }));
  if (r.des.type === 'cauris') {
    lignes.push(t('rCauris', { n: r.des.nbCauris, z: r.des.valeurZero }));
  } else if (r.des.type === 'de6') {
    lignes.push(t('rDe6'));
  } else {
    lignes.push(
      t('rDes', { n: r.des.nbDes, faces: r.des.faces.join(', ') }) +
        (r.des.faces.includes(0)
          ? r.des.valeurToutZero === 0 ? t('rKaapal') : t('rToutZero', { z: r.des.valeurToutZero })
          : '')
    );
  }
  lignes.push(t('rEntree', { v: r.valeursEntree.join(', ') }));
  lignes.push(
    t('rRejoue', { v: r.valeursRejouer.length ? r.valeursRejouer.join(', ') : t('rAucune') }) +
      (r.des.type === 'desLongs' && (r.doublesRejouer || []).length
        ? t('rAvec', { v: r.doublesRejouer.map((f) => t('rDouble', { f })).join(t('ou')) })
        : '') +
      (r.rejouerApresCapture ? t('rApresCapture') : '')
  );
  lignes.push(r.unPionParCase ? t('rUnPion') : t('rEmpiler'));
  if (!r.unPionParCase && r.groupeRentreEnsemble) lignes.push(t('rGroupe'));
  if (r.captureAvantInterieur) lignes.push(t('rCapture'));
  lignes.push(r.arriveeExacte ? t('rPile') : t('rPasPile'));
  return lignes;
}

