const COULEURS_CLES = { Rouge: 'rouge', Vert: 'vert', Jaune: 'jaune', Bleu: 'bleu' };

/** Nom d'un joueur : les noms par défaut (« Rouge », « Ordi vert »…) sont traduits. */
export function traduireNom(nom, t) {
  if (COULEURS_CLES[nom]) return t(COULEURS_CLES[nom]);
  const m = /^Ordi (rouge|vert|jaune|bleu)$/.exec(nom);
  if (m) return t('ordiCouleur', { couleur: t(m[1]).toLowerCase() });
  const j = /^Joueur (\d)$/.exec(nom);
  if (j) return t('joueurN', { n: j[1] });
  return nom;
}

/** Une ligne du journal (écrite en français par le moteur) dans la langue choisie. */
export function traduireJournal(ligne, t) {
  const N = (x) => traduireNom(x, t);
  const regles = [
    [/^La partie commence\. (.+) lance en premier\.$/, (m) => t('jDebut', { nom: N(m[1]) })],
    [/^(.+) fait (\d+|Kaapal) : aucun pion ne peut bouger, mais \1 rejoue\.$/, (m) => t('jFaitRejoue', { nom: N(m[1]), v: m[2] })],
    [/^(.+) fait Kaapal : les dés passent au joueur suivant\.$/, (m) => t('jKaapal', { nom: N(m[1]) })],
    [/^(.+) fait (\d+|Kaapal) : aucun pion ne peut bouger\.$/, (m) => t('jFaitBloque', { nom: N(m[1]), v: m[2] })],
    [/^(.+) fait entrer (\d+) pions d'un coup\.$/, (m) => t('jEntreGroupe', { nom: N(m[1]), n: m[2] })],
    [/^(.+) fait entrer un pion\.$/, (m) => t('jEntre', { nom: N(m[1]) })],
    [/^(.+) fait (\d+|Kaapal)\.$/, (m) => t('jFait', { nom: N(m[1]), v: m[2] })],
    [/^(.+) amène un pion au centre !$/, (m) => t('jCentre', { nom: N(m[1]) })],
    [/^(.+) capture (\d+) pions? de (.+) !$/, (m) => t('jCapture', { nom: N(m[1]), n: Number(m[2]), qui: m[3].split(' et ').map(N).join(t('et')) })],
    [/^(.+) a gagné la partie !$/, (m) => t('jGagnePartie', { nom: N(m[1]) })],
    [/^(.+) rejoue\.$/, (m) => t('jRejoue', { nom: N(m[1]) })],
  ];
  for (const [re, f] of regles) {
    const m = re.exec(ligne);
    if (m) return f(m);
  }
  return ligne;
}

