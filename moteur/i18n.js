/** Message d'erreur (réglages ou serveur) dans la langue choisie. */
export function traduireErreur(message, t) {
  const m = String(message || '').trim();
  const sansPoint = m.replace(/\.$/, '');
  for (const [fr, cle] of ERREURS) if (sansPoint === fr.replace(/\.$/, '')) return t(cle);
  const e = /^Aucune valeur d'entrée ne peut sortir avec ces dés \(valeurs possibles : (.+)\)\.$/.exec(m);
  if (e) return t('eEntreeImpossible', { v: e[1] });
  return m;
}

